    def _stage_assets(self, graph: ModuleGraph) -> list[str]:
        notes: list[str] = []
        has_unreal = any(m.language == "unreal" for m in graph.modules)
        for module in graph.modules:
            if module.language != "assets":
                continue
            if has_unreal:
                notes.append(
                    f"{module.module_id}: raw assets are NOT auto-imported into the "
                    "engine; Unreal import/cook owns them (use an editor import "
                    "or a Python import script run before cooking)."
                )
            else:
                notes.append(f"{module.module_id}: staged raw asset folder.")
        return notes

    def _entry_script(self, module: Module) -> str:
        """The module-relative script that carries the real main guard.

        Detection records the files it actually saw; ``main.py`` wins when it
        is one of them, otherwise the shallowest guarded file is used.
        """
        hints = ""
        for note in module.notes:
            if note.startswith("entry point hints (main guard):"):
                hints = note.split(":", 1)[1].strip()
                break
        candidates = [item.strip() for item in hints.split(",") if item.strip()]
        if not candidates:
            return ""

        def rank(rel: str) -> tuple[int, int, str]:
            name = Path(rel).name.lower()
            return (0 if name == "main.py" else 1, len(Path(rel).parts), rel)

        return sorted(candidates, key=rank)[0]

    def _assemble(self, graph: ModuleGraph, artifacts: dict[str, list[Path]], assembly_dir: Path) -> list[str]:
        notes: list[str] = []
        entry_id = graph.entry_point
        entry_module = graph.module(entry_id) if entry_id else None
        unreal_modules = [m for m in graph.modules if m.language == "unreal"]

        for module in unreal_modules:
            notes.append(
                f"unreal module {module.module_id}: assembly goes through Unreal's "
                "own BuildCookRun pipeline; ECE only stages external modules "
                "around it and reports the engine's absence honestly."
            )
            plan = self._unreal_plans.get(module.module_id)
            if plan is not None and plan.package_cmd and module.status == "built":
                self._progress("assemble", f"Unreal BuildCookRun for {module.module_id}")
                ok, output = execute_cmd(plan.package_cmd, cancel=self._cancel)
                notes.append(
                    f"unreal packaging for {module.module_id}: "
                    + ("BuildCookRun completed" if ok else f"BuildCookRun FAILED - {output.strip()[:400]}")
                )
                if ok:
                    staged = self.workspace.generated_dir / "unreal-package"
                    if staged.is_dir():
                        for item in sorted(staged.rglob("*")):
                            if not item.is_file():
                                continue
                            rel = item.relative_to(staged)
                            dest = assembly_dir / rel
                            dest.parent.mkdir(parents=True, exist_ok=True)
                            shutil.copy2(item, dest)
                        notes.append(f"archived game merged into the application: {len(list(staged.rglob('*')))} files")
            elif plan is not None and plan.package_cmd:
                notes.append(
                    f"unreal packaging for {module.module_id} skipped: the build "
                    "did not succeed, so per §7 no package is produced."
                )

        for module in graph.modules:
            if module.status != "built":
                continue
            try:
                root = self._module_root(module)
            except (StopIteration, EceError) as exc:
                notes.append(f"{module.module_id}: not assembled - {exc}")
                continue
            if module.language == "assets":
                if unreal_modules:
                    continue  # raw assets stay with Unreal's own import/cook
                out_assets = assembly_dir / "assets" / module.module_id
                out_assets.mkdir(parents=True, exist_ok=True)
                copied = 0
                for rel in module.source_files + module.asset_files:
                    src = root / rel
                    if not src.is_file():
                        continue
                    dst = out_assets / rel
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    try:
                        shutil.copy2(src, dst)
                        copied += 1
                    except OSError as exc:
                        notes.append(f"{module.module_id}: asset copy failed for {rel}: {exc}")
                notes.append(f"asset module {module.module_id}: staged {copied} files under assets/{module.module_id}")
                continue
            if module.language in {"assets", "unreal"}:
                continue
            if module.language == "python":
                target = assembly_dir if module.module_id == entry_id else assembly_dir / module.module_id
                target.mkdir(parents=True, exist_ok=True)
                for rel in module.source_files:
                    src = root / rel
                    dst = target / rel
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    try:
                        shutil.copy2(src, dst)
                    except OSError as exc:
                        notes.append(f"{module.module_id}: could not copy {rel}: {exc}")
                notes.append(f"python module {module.module_id} bundled as {target.name or 'app root'}")
            else:
                out_dir = assembly_dir / "modules" / module.module_id
                out_dir.mkdir(parents=True, exist_ok=True)
                for path in artifacts.get(module.module_id, []):
                    try:
                        shutil.copy2(path, out_dir / path.name)
                        notes.append(f"module {module.module_id}: deployed {path.name}")
                    except OSError as exc:
                        notes.append(f"module {module.module_id}: copy failed for {path.name}: {exc}")

        # A native entry point's own toolchain produced the executable; place
        # it (and its libraries) at the application root instead of hiding it
        # under modules/. ECE copies real artifacts, never renames one.
        if entry_module and entry_module.language not in {"python", "assets", "unreal"}:
            entry_files = artifacts.get(entry_id, [])
            placed: list[str] = []
            for path in entry_files:
                try:
                    shutil.copy2(path, assembly_dir / path.name)
                    placed.append(path.name)
                except OSError as exc:
                    notes.append(f"entry executable copy failed for {path.name}: {exc}")
            if placed:
                notes.append(
                    "entry artifacts placed at the application root: "
                    + ", ".join(sorted(placed))
                )
            executables = [p for p in entry_files if p.suffix.lower() == ".exe"]
            if not executables:
                notes.append(
                    f"entry module {entry_id} produced no executable; the package "
                    "contains its libraries under modules/ but there is no launch "
                    "command to invent, so none was generated"
                )

        # Shared libraries consumed with ctypes sit next to the entry point.
        for (consumer_id, _provider_id), plan in self._bridges.items():
            if plan.method != "shared-library":
                continue
            provider = plan.provider
            for path in artifacts.get(provider, []):
                if path.suffix.lower() in _SHARED_DEPLOY_SUFFIXES:
                    shutil.copy2(path, assembly_dir / path.name)
                    notes.append(
                        f"shared library of '{provider}' placed next to the entry point (consumer '{consumer_id}')"
                    )

        # Generated launcher for a Python entry point.
        if entry_module and entry_module.language == "python":
            script = self._entry_script(entry_module) or "main.py"
            launcher = assembly_dir / "run_application.py"
            launcher.write_text(
                _LAUNCHER_TEMPLATE.format(
                    app_name=self.workspace.config.name,
                    entry_id=entry_id,
                    entry_script=script,
                ),
                encoding="utf-8",
            )
            notes.append(f"generated launcher: {launcher.name} -> {script}")
        elif not entry_module and not unreal_modules:
            notes.append("no entry point: application files were assembled but no launcher was generated")
        return notes

    def _package(
        self,
        assembly_dir: Path,
        fmt: str,
        output: Path | None,
        graph: ModuleGraph,
        graph_snapshot: dict[str, Any] | None = None,
    ) -> tuple[Path, dict[str, Any]]:
        name = self.workspace.config.name or "application"
        version = self.workspace.config.version
        if output:
            destination = Path(output)
        else:
            suffix = {"ece": ".ece", "zip": ".zip"}.get(fmt, "")
            destination = self.workspace.generated_dir / f"{name}-{version}{suffix}"
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            destination.unlink()

        required_runtime: list[dict[str, Any]] = []
        for module in graph.modules:
            for req in module.required_runtime:
                required_runtime.append({"component": req, "module": module.module_id})
        entry = graph.module(graph.entry_point) if graph.entry_point else None

        manifest = Manifest(
            project_name=name,
            adapter_id="fusion",
            payload_type=f"fusion-application ({fmt})",
            platform=self.workspace.config.target_os,
            architecture=self.workspace.config.target_arch,
            configuration=self.workspace.config.configuration,
            entry_points=[{
                "module": graph.entry_point,
                "language": entry.language if entry else "",
                "kind": "module-entry",
                "script": (
                    self._entry_script(entry)
                    if entry is not None and entry.language == "python"
                    else ""
                ),
            }] if graph.entry_point else [],
            runtime_requirements=required_runtime,
            notes="Assembled by the ECE fusion engine.",
        )
        snapshot = graph_snapshot if graph_snapshot is not None else graph.as_dict()
        manifest.unknown_fields["fusion_modules"] = snapshot.get("modules", [])
        manifest.unknown_fields["fusion_graph"] = snapshot

        from ..packaging.collection import matches_any

        include = list(self.workspace.config.include or [])
        exclude = list(self.workspace.config.exclude or [])
        stats: dict[str, Any] = {
            "include": include,
            "exclude": exclude,
            "included_files": 0,
            "excluded_files": 0,
        }

        def keep(rel: str) -> bool:
            rel = rel.replace("\\", "/")
            if exclude and matches_any(rel, exclude):
                return False
            if include and not matches_any(rel, include):
                return False
            return True

        if fmt == "folder":
            kept, dropped = self._prune_folder(assembly_dir, keep)
            stats["included_files"] = kept
            stats["excluded_files"] = dropped
            return assembly_dir, stats
        if fmt not in {"ece", "zip"}:
            raise EceError(f"Unsupported package format {fmt!r}; nothing was written.")

        selected: list[Path] = []
        for path in sorted(assembly_dir.rglob("*")):
            if not path.is_file():
                continue
            if keep(path.relative_to(assembly_dir).as_posix()):
                selected.append(path)
            else:
                stats["excluded_files"] += 1
        stats["included_files"] = len(selected)

        if fmt == "ece":
            items = [
                PayloadItem(
                    path=path.relative_to(assembly_dir).as_posix(),
                    source=path,
                    executable=path.suffix.lower() == ".exe",
                )
                for path in selected
            ]
            ContainerWriter().write(destination, items, manifest, overwrite=True)
            return destination, stats
        import zipfile

        stamp = _zip_timestamp()
        with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as zf:
            for path in selected:
                arcname = path.relative_to(assembly_dir.parent).as_posix()
                if stamp is None:
                    zf.write(path, arcname)
                    continue
                info = zipfile.ZipInfo(arcname, date_time=stamp)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (path.stat().st_mode & 0xFFFF) << 16
                zf.writestr(info, path.read_bytes())
        return destination, stats

    def _prune_folder(self, root: Path, keep: Callable[[str], bool]) -> tuple[int, int]:
        """Apply include/exclude rules to a folder output; returns kept/dropped."""
        kept = dropped = 0
        for path in sorted((p for p in root.rglob("*") if p.is_file()), reverse=True):
            rel = path.relative_to(root).as_posix()
            if keep(rel):
                kept += 1
                continue
            try:
                path.unlink()
                dropped += 1
            except OSError as exc:
                logger.debug("could not remove excluded file %s: %s", path, exc)
                kept += 1
        for path in sorted((p for p in root.rglob("*") if p.is_dir()), reverse=True):
            try:
                path.rmdir()  # only removes directories left empty
            except OSError:
                pass
        return kept, dropped

    def _validate_ece(self, package_path: Path) -> list[str]:
        findings: list[str] = []
        try:
            reader = ContainerReader(package_path)
            reader.open()
        except Exception as exc:
            return [f"error: package could not be parsed: {exc}"]
        try:
            findings.extend(f"error: {e}" for e in reader.verify_all())
            manifest = reader.manifest
        finally:
            reader.close()
        if manifest is None:
            findings.append("error: package has no manifest")
        elif manifest.payload_type and "fusion" not in manifest.payload_type:
            findings.append(f"warning: unexpected payload_type {manifest.payload_type!r}")
        return findings
