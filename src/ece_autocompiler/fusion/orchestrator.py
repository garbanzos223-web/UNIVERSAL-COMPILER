def _zip_timestamp() -> tuple[int, int, int, int, int, int] | None:
    """A fixed ZIP date/time when ``SOURCE_DATE_EPOCH`` is set."""
    raw = os.environ.get("SOURCE_DATE_EPOCH", "").strip()
    if not raw:
        return None
    try:
        moment = time.gmtime(int(raw))
    except (OverflowError, OSError, ValueError):
        return None
    year = max(1980, moment.tm_year)
    return (year, moment.tm_mon, moment.tm_mday, moment.tm_hour, moment.tm_min, moment.tm_sec)


def _artifact_kind(path: Path) -> str:
    suffix = path.suffix.lower()
    if suffix == ".exe":
        return "executable"
    if suffix in {".dll", ".so", ".pyd", ".node"}:
        return "shared-library"
    if suffix in {".lib", ".a"}:
        return "static-library"
    return "file"


@dataclass
class FusionResult:
    ok: bool
    workspace: FusionWorkspace
    graph: ModuleGraph
    bridges: dict[tuple[str, str], BridgePlan] = field(default_factory=dict)
    compatibility: CompatibilityReport = field(default_factory=CompatibilityReport)
    package_path: str = ""
    package_kind: str = ""
    assembly_dir: str = ""
    report: dict[str, Any] = field(default_factory=dict)
    messages: list[str] = field(default_factory=list)
    validation: list[str] = field(default_factory=list)


class FusionOrchestrator:
    def __init__(
        self,
        workspace: FusionWorkspace,
        *,
        progress: ProgressFn | None = None,
        cancel: Any = None,
    ) -> None:
        self.workspace = workspace
        self._progress = progress or (lambda stage, detail: None)
        self._cancel = cancel
        self.registry = AdapterRegistry()
        self._bridges: dict[tuple[str, str], BridgePlan] = {}
        self._unreal_plans: dict[str, Any] = {}
        # A workspace may expose the same folder through several modules
        # (CMake subprojects, for example); scan it once, not once per use.
        self._scan_cache: dict[str, Any] = {}
        self._max_parallel: int | None = None

    def _cancelled(self) -> bool:
        return bool(self._cancel is not None and self._cancel.is_set())

    # ------------------------------------------------------------------
    # main entry
    # ------------------------------------------------------------------

    def run(
        self,
        *,
        package_format: str | None = None,
        output: Path | None = None,
        use_cache: bool = True,
        repair_attempts: int = 0,
        max_parallel: int | None = None,
    ) -> FusionResult:
        fmt = package_format or self.workspace.config.package_format
        messages: list[str] = []
        start = time.time()
        self._max_parallel = max_parallel
        if fmt not in _PACKAGE_FORMATS:
            return self._fail(
                [
                    f"Unsupported fusion package format {fmt!r}. Fusion builds "
                    "produce an .ece package, a ZIP archive or an application "
                    "folder. A single .exe requires a native entry point or a "
                    "real packager; ECE will not rename an archive to .exe."
                ],
                messages,
                fmt,
            )

        self._progress("verify", "Checking workspace integrity")
        problems = self.workspace.verify()
        if problems:
            return self._fail(problems, messages, fmt)

        self._progress("graph", "Building the module graph")
        graph = build_graph(self.workspace)
        # Structural snapshot for the package manifest. It is taken before
        # any build mutates statuses/notes, so two runs over identical inputs
        # produce the same manifest (reproducibility).
        package_graph_snapshot = graph.as_dict()
        conflicts_snapshot = list(graph.conflicts)
        self.workspace.conflicts()  # duplicate/conflict detection is logged

        self._progress("bridges", "Planning module integrations")
        self._bridges = plan_all(graph, self.workspace)

        self._progress("compat", "Validating compatibility")
        compat = self.validate_compatibility(graph)
        fatal = [c["message"] for c in compat.checks if c["level"] == "error"]
        if fatal:
            return self._fail(fatal, messages, fmt, graph=graph, bridges=self._bridges, compat=compat)

        self._progress("build", "Building modules in dependency order")
        cache = CacheState.load(self.workspace.root)
        (
            module_tasks,
            cache_hits,
            dep_keys,
            module_repairs,
            module_tests,
            cancelled,
        ) = self._build_modules(graph, cache=cache, repair_attempts=repair_attempts)
        graph.tasks = [module_tasks[mid] for mid in graph.order if mid in module_tasks]
        if cancelled:
            messages.append("Build cancelled by user.")

        artifacts, artifact_paths = self._collect_artifacts(graph, module_tasks)
        artifact_records = self._record_artifacts(graph, artifact_paths)
        if use_cache:
            for module in graph.modules:
                task = module_tasks.get(module.module_id)
                if task is None or task.status != "built":
                    continue
                key = dep_keys.get(module.module_id, "")
                if not key:
                    continue
                outputs = [str(p) for p in artifact_paths.get(module.module_id, [])]
                if not outputs:
                    root = self._module_root(module)
                    outputs = [str(root / rel) for rel in module.source_files[:20]]
                digests = {
                    record["path"]: record["sha256"]
                    for record in artifact_records
                    if record.get("module") == module.module_id and record.get("sha256")
                }
                cache.record(module.module_id, key, outputs, digests=digests)
            cache.save()
        self._verify_integration_architecture(graph, bridges=self._bridges, artifact_paths=artifact_paths)

        self._progress("assets", "Staging assets")
        asset_notes = self._stage_assets(graph)

        self._progress("assemble", "Assembling the application directory")
        assembly_dir = self.workspace.generated_dir / "app"
        if assembly_dir.exists():
            shutil.rmtree(assembly_dir)
        assembly_dir.mkdir(parents=True, exist_ok=True)
        assembly_notes = self._assemble(graph, artifacts, assembly_dir)

        package_path: Path | None = None
        package_error = ""
        package_filters: dict[str, Any] = {}
        if cancelled:
            # A cancelled build must not leave something that looks like a
            # complete package. The assembled tree stays for inspection.
            messages.append("No package was produced because the build was cancelled.")
        else:
            self._progress("package", f"Packaging as {fmt}")
            try:
                package_path, package_filters = self._package(
                    assembly_dir, fmt, output, graph, package_graph_snapshot
                )
            except Exception as exc:
                logger.debug("packaging failed: %s", exc)
                package_error = str(exc)

        validation: list[str] = []
        if package_path and package_path.exists() and fmt == "ece":
            validation = self._validate_ece(package_path)
        package_record = self._record_package(package_path, fmt)

        # Success requires every module to be built. "skipped" means a
        # dependency failed or the user cancelled; that is not success.
        ok = (
            bool(module_tasks)
            and all(task.status == "built" for task in module_tasks.values())
            and not cancelled
            and not package_error
            and bool(package_record)
            and not [v for v in validation if v.startswith("error")]
        )
        total_seconds = round(time.time() - start, 3)

        report = {
            "generated_utc": now_utc(),
            "workspace": str(self.workspace.root),
            "application": self.workspace.config.name,
            "version": self.workspace.config.version,
            "entry_point": graph.entry_point,
            "package_format": fmt,
            "package_path": str(package_path) if package_path else "",
            "assembly_dir": str(assembly_dir),
            "duration_seconds": total_seconds,
            "tasks": [t.to_dict() for t in module_tasks.values()],
            "ok": ok,
            "graph": graph.as_dict(),
            "bridges": [
                {"consumer": c, "provider": p, **plan.to_dict()}
                for (c, p), plan in sorted(self._bridges.items())
            ],
            "compatibility": {"checks": compat.checks, "warnings": compat.warnings},
            "unreal_plans": {
                module_id: plan.to_dict() for module_id, plan in self._unreal_plans.items()
            },
            "cache_hits": sorted(cache_hits),
            "cancelled": cancelled,
            "parallel_jobs": self._worker_count(),
            "artifacts": artifact_records,
            "package_artifact": package_record,
            "package_filters": package_filters,
            "module_repairs": module_repairs,
            "module_tests": module_tests,
            "assets": asset_notes,
            "assembly": assembly_notes,
            "planning_conflicts": conflicts_snapshot,
            "package_error": package_error,
            "validation": validation,
        }
        report_path = self.workspace.generated_dir / "report.json"
        # Atomic write + .bak: a crash or a full disk must not leave a
        # truncated report behind.
        write_json_atomic(report_path, report)
        report["report_path"] = str(report_path)

        if package_error:
            messages.append(f"Packaging failed: {package_error}")
        messages.extend(conflicts_snapshot)
        if graph.cycles:
            messages.append("Dependency cycle present; module order may be incomplete.")

        return FusionResult(
            ok=ok,
            workspace=self.workspace,
            graph=graph,
            bridges=self._bridges,
            compatibility=compat,
            package_path=str(package_path) if package_path else "",
            package_kind=fmt,
            assembly_dir=str(assembly_dir),
            report=report,
            messages=messages,
            validation=validation,
        )

    def _fail(
        self,
        problems: list[str],
        messages: list[str],
        fmt: str,
        *,
        graph: ModuleGraph | None = None,
        bridges: dict | None = None,
        compat: CompatibilityReport | None = None,
    ) -> FusionResult:
        return FusionResult(
            ok=False,
            workspace=self.workspace,
            graph=graph or ModuleGraph(),
            bridges=bridges or {},
            compatibility=compat or CompatibilityReport(),
            package_kind=fmt,
            messages=messages + problems,
            report={"problems": problems},
        )

    # ------------------------------------------------------------------
    # building one module
    # ------------------------------------------------------------------

    def _cache_key_for(self, module: Module, dep_keys: dict[str, str]) -> str:
        """Compute a module's incremental cache key, from real file hashes."""
        try:
            root = self._module_root(module)
        except (StopIteration, EceError):
            return ""
        sources = [root / rel for rel in module.source_files if rel]
        config = self.workspace.config
        return compute_key(
            module.module_id,
            sources,
            adapter_id=module.adapter_id,
            configuration=module.build_configuration,
            target_arch=module.target_architecture,
            dependency_keys={
                dep: dep_keys.get(dep, "")
                for dep in module.dependencies
            },
            settings={
                "build_tool": module.build_tool,
                "optimization_profile": config.optimization_profile,
                "toolchain": self._toolchain_identity(module),
            },
        )

    def _toolchain_identity(self, module: Module) -> dict[str, Any]:
        """The real toolchain that builds this module (for cache + report)."""
        from ..detection import get_tool
        from ..toolchain_hints import ADAPTER_TO_TOOL

        tool_id = ADAPTER_TO_TOOL.get(module.adapter_id, "") or module.build_tool
        if not tool_id:
            return {}
        override = self.workspace.config.toolchains.get(tool_id, "")
        info = get_tool(tool_id)
        identity: dict[str, Any] = {"id": tool_id}
        if override:
            identity["override"] = str(override)
        if info is not None:
            identity["found"] = bool(info.found)
            identity["path"] = info.path or ""
            identity["version"] = info.version or ""
        return identity

    def _worker_count(self) -> int:
        """Bounded parallelism: never more than 16 concurrent module builds."""
        if self._max_parallel is not None:
            requested = int(self._max_parallel)
        else:
            requested = int(getattr(self.workspace.config, "max_parallel", 0) or 0)
        if requested > 0:
            return min(requested, 16)
        return max(1, min(4, os.cpu_count() or 1))

    def _cache_keys(self, graph: ModuleGraph) -> dict[str, str]:
        """Compute every module cache key once, in dependency order."""
        keys: dict[str, str] = {}
        for module_id in graph.order:
            module = graph.module(module_id)
            if module is None:
                continue
            key = self._cache_key_for(module, keys)
            if key:
                keys[module_id] = key
        return keys

    def _build_modules(
        self,
        graph: ModuleGraph,
        *,
        cache: CacheState,
        repair_attempts: int,
    ) -> tuple[
        dict[str, BuildTask],
        set[str],
        dict[str, str],
        dict[str, dict],
        dict[str, dict],
        bool,
    ]:
        """Build every module, running independent modules concurrently.

        A module only starts after its dependencies finished. Modules that
        share a directory never run at the same time (they may write to the
        same build tree). A failed dependency skips its dependents instead of
        building them against a missing artifact.
        """
        index = {module.module_id: module for module in graph.modules}
        keys = self._cache_keys(graph)
        module_tasks: dict[str, BuildTask] = {}
        module_repairs: dict[str, dict] = {}
        module_tests: dict[str, dict] = {}
        cache_hits: set[str] = set()
        pending = [module_id for module_id in graph.order if module_id in index]
        done: set[str] = set()
        failed: set[str] = set()
        cancelled = False
        workers = self._worker_count()

        # A cycle is not a build order. Its members are reported as failed
        # instead of being built in an arbitrary, possibly wrong sequence.
        cycle_errors: dict[str, str] = {}
        for cycle in graph.cycles:
            label = " -> ".join(cycle)
            for member in cycle:
                if member in index and member not in cycle_errors:
                    cycle_errors[member] = (
                        f"dependency cycle detected ({label}); this module was NOT "
                        "built. Break the cycle (or remove the false dependency) "
                        "and run the build again."
                    )

        while pending:
            if self._cancelled():
                cancelled = True
                break
            for module_id in list(pending):
                if module_id not in cycle_errors:
                    continue
                module = index[module_id]
                task = BuildTask(
                    task_id=f"module:{module_id}",
                    module_id=module_id,
                    title=f"build {module_id} ({module.build_tool or module.language})",
                    status="failed",
                    error=cycle_errors[module_id],
                )
                module.status = "failed"
                module.notes.append("not built: dependency cycle")
                module_tasks[module_id] = task
                cache.entries.pop(module_id, None)
                pending.remove(module_id)
                done.add(module_id)
                failed.add(module_id)
                self._progress("build", f"{module_id}: failed (dependency cycle)")
            if not pending:
                break
            ready = [
                module_id
                for module_id in pending
                if all(
                    dep in done or dep in failed or dep not in index
                    for dep in index[module_id].dependencies
                )
            ]
            if not ready:
                # Defensive: every remaining module waits for another one but
                # no cycle was recorded. Never guess an order; fail honestly.
                for module_id in list(pending):
                    module = index[module_id]
                    module.status = "failed"
                    module.notes.append("not built: dependency order is unresolvable")
                    module_tasks[module_id] = BuildTask(
                        task_id=f"module:{module_id}",
                        module_id=module_id,
                        title=f"build {module_id}",
                        status="failed",
                        error=(
                            "dependency order could not be resolved; the module was "
                            "NOT built. Check its declared dependencies."
                        ),
                    )
                    cache.entries.pop(module_id, None)
                    pending.remove(module_id)
                    failed.add(module_id)
                break

            blocked = [
                module_id
                for module_id in ready
                if any(dep in failed for dep in index[module_id].dependencies)
            ]
            for module_id in blocked:
                module = index[module_id]
                blockers = [dep for dep in module.dependencies if dep in failed]
                task = BuildTask(
                    task_id=f"module:{module_id}",
                    module_id=module_id,
                    title=f"build {module_id} ({module.build_tool or module.language})",
                    status="skipped",
                    error=(
                        "not built because dependency "
                        + ", ".join(blockers)
                        + " failed; the application cannot be assembled from it"
                    ),
                )
                task.depends_on = [f"module:{dep}" for dep in module.dependencies]
                module.status = "skipped"
                module.notes.append("skipped: a dependency failed")
                module_tasks[module_id] = task
                pending.remove(module_id)
                done.add(module_id)
                failed.add(module_id)
                self._progress("build", f"{module_id}: skipped (dependency failed)")
            ready = [module_id for module_id in ready if module_id not in blocked]
            if not ready:
                continue

            batch = self._batch_without_root_conflicts(ready, index)
            if workers > 1 and len(batch) > 1:
                self._progress(
                    "build",
                    "Building " + ", ".join(batch) + f" (up to {min(workers, len(batch))} in parallel)",
                )
            outcomes: dict[str, tuple[BuildTask, dict | None, dict | None]] = {}
            if workers == 1 or len(batch) == 1:
                for module_id in batch:
                    outcomes[module_id] = self._build_one(
                        graph,
                        index[module_id],
                        cache=cache,
                        cache_key=keys.get(module_id, ""),
                        repair_attempts=repair_attempts,
                    )
            else:
                with ThreadPoolExecutor(
                    max_workers=min(workers, len(batch)),
                    thread_name_prefix="ece-fusion",
                ) as pool:
                    futures = {
                        pool.submit(
                            self._build_one,
                            graph,
                            index[module_id],
                            cache=cache,
                            cache_key=keys.get(module_id, ""),
                            repair_attempts=repair_attempts,
                        ): module_id
                        for module_id in batch
                    }
                    for future in as_completed(futures):
                        module_id = futures[future]
                        try:
                            outcomes[module_id] = future.result()
                        except Exception as exc:  # never lose one module's failure
                            logger.debug("module %s raised during build: %s", module_id, exc)
                            module = index[module_id]
                            module.status = "failed"
                            outcomes[module_id] = (
                                BuildTask(
                                    task_id=f"module:{module_id}",
                                    module_id=module_id,
                                    title=f"build {module_id}",
                                    status="failed",
                                    error=f"internal build error: {exc}",
                                ),
                                None,
                                None,
                            )

            for module_id in batch:
                task, repair_entry, test_entry = outcomes[module_id]
                module_tasks[module_id] = task
                if repair_entry is not None:
                    module_repairs[module_id] = repair_entry
                if test_entry is not None:
                    module_tests[module_id] = test_entry
                if task.cached:
                    cache_hits.add(module_id)
                if task.status != "built":
                    # Do not serve a stale cache entry for a failed module.
                    cache.entries.pop(module_id, None)
                    failed.add(module_id)
                done.add(module_id)
                pending.remove(module_id)
                suffix = " (cached)" if task.cached else ""
                self._progress("build", f"{module_id}: {task.status}{suffix}")

        if cancelled:
            for module_id in list(pending):
                module = index[module_id]
                module.status = "skipped"
                module.notes.append("skipped: build cancelled by user")
                module_tasks[module_id] = BuildTask(
                    task_id=f"module:{module_id}",
                    module_id=module_id,
                    title=f"build {module_id}",
                    status="skipped",
                    error="build cancelled by user before this module ran",
                )
                pending.remove(module_id)

        return module_tasks, cache_hits, keys, module_repairs, module_tests, cancelled

    def _batch_without_root_conflicts(
        self, ready: list[str], index: dict[str, Module]
    ) -> list[str]:
        """Pick one module per directory so concurrent builds never collide."""
        batch: list[str] = []
        roots: set[str] = set()
        for module_id in ready:
            module = index[module_id]
            try:
                root = str(self._module_root(module))
            except (StopIteration, OSError, EceError):
                root = f"__unresolved__:{module_id}"
            if root in roots:
                continue
            roots.add(root)
            batch.append(module_id)
        return batch

    def _build_one(
        self,
        graph: ModuleGraph,
        module: Module,
        *,
        cache: CacheState,
        cache_key: str,
        repair_attempts: int,
    ) -> tuple[BuildTask, dict | None, dict | None]:
        """Build one module, repair it when allowed, then run its tests."""
        task = self._build_module(graph, module, cache=cache, cache_key=cache_key)
        repair_entry: dict | None = None
        if task.status == "failed" and repair_attempts > 0 and module.language not in {
            "assets",
            "unreal",
        }:
            try:
                module_root = self._module_root(module)
            except (StopIteration, EceError) as exc:
                logger.info("repair skipped for %s: %s", module.module_id, exc)
                module_root = None
            if module_root is not None:
                logger.info("module %s failed; running the repair engine", module.module_id)
                result_entry = repair_module(
                    module,
                    module_root,
                    self.workspace,
                    max_attempts=repair_attempts,
                    progress=None,
                )
                repair_entry = result_entry.to_dict()
                if result_entry.repaired:
                    # Force a rebuild: a cache hit would hide the repair.
                    task = self._build_module(graph, module)
        test_entry: dict | None = None
        if task.status == "built" and not task.cached:
            test_cmd = self.workspace.config.test_commands.get(module.module_id, "")
            if test_cmd:
                tests_ok, tests_summary = self._run_module_test(module, test_cmd)
                test_entry = {"ok": tests_ok, "summary": tests_summary}
        return task, repair_entry, test_entry

    def _scan_root(self, root: Path) -> Any:
        """Scan a module root once per orchestrator run."""
        key = str(root)
        result = self._scan_cache.get(key)
        if result is None:
            result = scan(root)
            self._scan_cache[key] = result
        return result

    def _build_module(
        self,
        graph: ModuleGraph,
        module: Module,
        *,
        cache: CacheState | None = None,
        cache_key: str = "",
    ) -> BuildTask:
        if module.language == "assets":
            module.status = "built"
            return BuildTask(
                task_id=f"module:{module.module_id}",
                module_id=module.module_id,
                title=f"stage assets ({module.module_id})",
                kind="asset",
                status="built",
            )
        if module.language == "unreal":
            return self._build_unreal(module)

        task = BuildTask(
            task_id=f"module:{module.module_id}",
            module_id=module.module_id,
            title=f"build {module.module_id} ({module.build_tool or module.language})",
        )
        for dep in module.dependencies:
            task.depends_on.append(f"module:{dep}")

        # Dependency-aware cache: rebuild only when inputs actually changed.
        if cache is not None and cache_key and find_cache_hit(module.module_id, cache, cache_key):
            task.status = "built"
            task.cached = True
            module.status = "built"
            module.notes.append("cached: inputs and dependencies unchanged since the last build")
            return task

        try:
            root = self._module_root(module)
        except (StopIteration, EceError) as exc:
            task.status = "failed"
            task.error = f"Module root could not be resolved safely: {exc}"
            module.status = "failed"
            return task
        try:
            scan_root = self._scan_root(root)
        except Exception as exc:
            task.status = "failed"
            task.error = f"Scan failed for module root: {exc}"
            module.status = "failed"
            return task
        adapter = None
        for d in self.registry.detect(root, scan_root):
            if d.adapter_id == module.adapter_id:
                adapter = self.registry.for_detected(d)
                break
        if adapter is None:
            task.status = "failed"
            task.error = f"No adapter plans builds for module {module.module_id}."
            module.status = "failed"
            return task

        requirements = adapter.inspect_requirements(root)
        if not requirements.ready:
            missing = [f"{r.id}: {r.install_hint}" for r in requirements.requirements if not r.found]
            task.status = "failed"
            task.error = "Toolchain missing; module NOT built (no fake success): " + "; ".join(missing)
            module.status = "failed"
            return task

        try:
            plan = adapter.create_build_plan(root)
        except Exception as exc:
            task.status = "failed"
            task.error = f"Build plan failed: {exc}"
            module.status = "failed"
            return task
        for step in plan.steps:
            task.command.append(" ".join(str(a) for a in step.cmd_args))

        log_path = self.workspace.generated_dir / f"build-{module.module_id}.log"
        started = time.time()
        try:
            result = adapter.execute_build(
                plan, progress=None, cancel=self._cancel, log_path=log_path, consent_granted=True
            )
        except EceError as exc:
            task.duration_seconds = round(time.time() - started, 3)
            task.status = "failed"
            task.error = f"Build was not run: {exc}"
            module.status = "failed"
            return task
        task.duration_seconds = round(time.time() - started, 3)
        task.status = "built" if result.ok else "failed"
        detail = getattr(result, "message", "") or ""
        if not detail and not result.ok:
            detail = "; ".join(list(getattr(result, "errors", []) or [])[:3]) or "build failed"
        task.error = "" if result.ok else detail
        module.status = "built" if result.ok else "failed"
        return task

    def _build_unreal(self, module: Module) -> BuildTask:
        """Build an Unreal module through the engine's own pipeline (§7)."""
        task = BuildTask(
            task_id=f"module:{module.module_id}",
            module_id=module.module_id,
            title=f"unreal build ({module.module_id})",
        )
        config = self.workspace.config
        toolchains = getattr(config, "toolchains", {})
        engine_hint = Path(toolchains["unreal-engine"]) if toolchains.get("unreal-engine") else None
        plan = plan_unreal_module(
            module,
            self._module_root(module),
            configuration={  # unreal uses its own configuration names
                "release": "Development",
                "debug": "Debug",
            }.get(config.configuration, "Development"),
            package_unreal=config.package_unreal,
            archive_dir=self.workspace.generated_dir / "unreal-package",
            engine_root_hint=engine_hint,
        )
        for cmd_name, cmd in (("build", plan.build_cmd), ("package", plan.package_cmd)):
            if cmd:
                task.command.append(" ".join(cmd))
        if not plan.ready:
            task.status = "failed"
            task.error = "Unreal build NOT run (engine/toolchain missing): " + "; ".join(plan.missing)
            module.status = "failed"
            module.notes.append("unreal plan: not run on this host")
            return task
        module.notes.append(f"unreal engine: {plan.engine_root} ({plan.engine_version})")
        if plan.asset_script_cmd:
            task.command.append("asset script cmd configured (editor, build-time only)")
        self._unreal_plans[module.module_id] = plan
        started = time.time()
        ok, output = execute_cmd(plan.build_cmd, cancel=self._cancel)
        task.duration_seconds = round(time.time() - started, 3)
        task.status = "built" if ok else "failed"
        task.error = "" if ok else output.strip()[:800]
        module.status = "built" if ok else "failed"
        return task

    def _run_module_test(self, module: Module, test_cmd: str) -> tuple[bool, str]:
        """Run one module's configured test command; never hides a failure."""
        from ..adapters.base import BuildPlanStep
        from ..build.process import run_command
        import shlex

        raw_tokens = shlex.split(test_cmd, posix=False)
        argv = [
            token[1:-1]
            if len(token) >= 2 and token[0] == token[-1] and token[0] in {'"', "'"}
            else token
            for token in raw_tokens
        ]
        if not argv:
            return False, "empty test command"
        if argv[0].lower() in {"python", "python3", "py"}:
            argv[0] = sys.executable
        step = BuildPlanStep(
            id="module-test",
            title=f"tests for {module.module_id}",
            cmd_args=argv,
            workdir=self._module_root(module),
            timeout=600,
            requires_approval=False,
        )
        try:
            result = run_command(
                [step],
                self._module_root(module),
                consent_granted=True,
                log_path=self.workspace.generated_dir / f"test-{module.module_id}.log",
            )
        except Exception as exc:
            return False, f"test could not run: {exc}"
        lines: list[str] = []
        for executed in result.step_results:
            lines.extend(executed.output_lines[-40:])
        summary = ("exit=" + ("ok" if result.ok else "fail") + " " + "\n".join(lines))[-400:]
        return bool(result.ok), summary

    def _module_root(self, module: Module) -> Path:
        """The module's directory, guaranteed to stay inside its input.

        Module roots come from project detection; a malformed manifest must
        never make the engine scan, build or copy files outside the imported
        input.
        """
        inp = next(i for i in self.workspace.inputs if i.input_id == module.input_id)
        loc = self.workspace.input_location(inp).resolve()
        if not module.root:
            return loc
        root = (loc / module.root).resolve()
        if root != loc and loc not in root.parents:
            raise EceError(
                f"Module {module.module_id!r} declares a root outside its input "
                f"({module.root!r}); refusing to use it."
            )
        return root

    def _collect_artifacts(
        self, graph: ModuleGraph, tasks: dict[str, BuildTask]
    ) -> tuple[dict[str, list[Path]], dict[str, list[Path]]]:
        """Find a built module's real artifacts and verify declared outputs.

        A build command that exits with code zero is not proof that it made
        the artifact it declared. When a compiled module declares outputs and
        none of them exists on disk, the module is marked failed: ECE never
        reports success for an artifact that is not there.
        """
        outputs: dict[str, list[Path]] = {}
        for module in graph.modules:
            task = tasks.get(module.module_id)
            if task is None or task.status != "built":
                continue
            try:
                root = self._module_root(module)
            except (StopIteration, EceError) as exc:
                task.status = "failed"
                task.error = f"module root could not be resolved for artifact checks: {exc}"
                module.status = "failed"
                continue
            found: list[Path] = []
            for name in module.output_artifacts:
                candidate = root / name
                for suffix in _ARTIFACT_SUFFIXES:
                    alternative = candidate.with_suffix(suffix)
                    if alternative.is_file() and alternative not in found:
                        found.append(alternative)
            if not found:
                for folder_name in ("bin", "build", "dist", "target"):
                    folder = root / folder_name
                    if not folder.is_dir():
                        continue
                    for candidate in sorted(folder.rglob("*")):
                        if (
                            candidate.is_file()
                            and candidate.suffix.lower() in _ARTIFACT_SUFFIXES
                        ):
                            found.append(candidate)
                            if len(found) >= 200:
                                break
                    if len(found) >= 200:
                        break
            declares_outputs = bool(module.output_artifacts)
            expects_artifact = declares_outputs and module.language not in _NO_ARTIFACT_LANGUAGES
            if expects_artifact and not found:
                task.status = "failed"
                task.error = (
                    "the build command reported success but the declared artifact(s) "
                    + ", ".join(module.output_artifacts)
                    + " were not found on disk; the module is NOT considered built"
                )
                module.status = "failed"
                module.notes.append("artifact verification failed: declared outputs are missing")
                continue
            if found:
                found = found[:200]
                task.outputs = [str(path) for path in found]
                outputs[module.module_id] = found
        return outputs, outputs

    def _record_artifacts(
        self, graph: ModuleGraph, artifact_paths: dict[str, list[Path]]
    ) -> list[dict[str, Any]]:
        """Record size and SHA-256 for every real artifact (Phase 4.4)."""
        records: list[dict[str, Any]] = []
        for module in graph.modules:
            for path in artifact_paths.get(module.module_id, []):
                record: dict[str, Any] = {
                    "module": module.module_id,
                    "path": str(path),
                    "language": module.language,
                    "target": f"{module.target_platform}/{module.target_architecture}",
                    "configuration": module.build_configuration,
                    "kind": _artifact_kind(path),
                    "toolchain": self._toolchain_identity(module),
                }
                try:
                    record["size"] = path.stat().st_size
                    record["sha256"] = sha256_file(path)
                except OSError as exc:
                    record["size"] = 0
                    record["sha256"] = ""
                    record["error"] = str(exc)
                records.append(record)
        return records

    def _record_package(self, package_path: Path | None, fmt: str) -> dict[str, Any]:
        """Hash the final package; a directory gets a manifest-style record."""
        if package_path is None or not package_path.exists():
            return {}
        record: dict[str, Any] = {
            "path": str(package_path),
            "format": fmt,
            "platform": self.workspace.config.target_os,
            "architecture": self.workspace.config.target_arch,
            "configuration": self.workspace.config.configuration,
        }
        if package_path.is_file():
            try:
                record["size"] = package_path.stat().st_size
                record["sha256"] = sha256_file(package_path)
            except OSError as exc:
                record["size"] = 0
                record["sha256"] = ""
                record["error"] = str(exc)
        else:
            files = [p for p in package_path.rglob("*") if p.is_file()]
            record["size"] = sum(p.stat().st_size for p in files)
            record["sha256"] = ""
            record["file_count"] = len(files)
            record["note"] = (
                "directory output: no single hash; the individual files are "
                "recorded in the artifacts list"
            )
        return record

