"""Fusion orchestrator: assembles one application from the module graph.

The pipeline follows the assembly order in docs/FUSION.md:

1. Verify the workspace and its inputs.
2. Build the module graph (imports, manifests, cycles, order).
3. Plan the bridges between pairs of modules.
4. Validate compatibility (architecture, runtime, toolchains).
5. Build every module with its own real toolchain, in dependency order.
6. Process/stage assets.
7. Assemble the application directory.
8. Package it (ECE container, ZIP or folder).
9. Validate the package and write the detailed report.

Every step records what actually happened; a step that could not run says so.
"""

from __future__ import annotations

import json
import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

from ..adapters.registry import AdapterRegistry
from ..container import ContainerReader, ContainerWriter, Manifest, PayloadItem
from ..detection import scan
from .bridges import BridgePlan, plan_all, verify_architecture_pair
from .compatibility import (
    CompatibilityReport,
    check_dotted_runtime,
    check_python_extension_arch,
    check_unreal_engine,
    prebuilt_architecture_conflicts,
)
from .models import BuildTask, Module, ModuleGraph, now_utc
from .modules import build_graph
from .workspace import FusionWorkspace

logger = logging = __import__("logging").getLogger(__name__)

ProgressFn = Callable[[str, str], None]

_SHARED_DEPLOY_SUFFIXES = {".pyd", ".dll", ".so", ".node"}

_LAUNCHER_TEMPLATE = '''"""Generated by the ECE fusion engine - launcher for '{app_name}'.

Puts every bundled module on the import path and runs the entry module's
``main.py`` (the file that carries the ``__main__`` guard). Generated; edit
``ece-project.json`` instead of this file.
"""

import runpy
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENTRY = HERE / "{entry_id}"
for path in (HERE, ENTRY):
    if path.is_dir():
        sys.path.insert(0, str(path))

targets = [ENTRY / "main.py", HERE / "main.py"]
for target in targets:
    if target.exists():
        runpy.run_path(str(target), run_name="__main__")
        break
else:
    raise SystemExit(
        "No main.py for module '{entry_id}'. Set 'entry_point' in "
        "ece-project.json to a module whose main script is main.py."
    )
'''


@dataclass
class FusionResult:
    ok: bool
    workspace: FusionWorkspace
    graph: ModuleGraph
    bridges: dict[tuple[str, str], BridgePlan] = field(default_factory=dict)
    compatibility: CompatibilityReport = field(default_factory=CompatibilityReport)
    package_path: str = ""
    package_kind: str = ""
    assembly_dir: str = ""
    report: dict[str, Any] = field(default_factory=dict)
    messages: list[str] = field(default_factory=list)
    validation: list[str] = field(default_factory=list)


class FusionOrchestrator:
    def __init__(
        self,
        workspace: FusionWorkspace,
        *,
        progress: ProgressFn | None = None,
        cancel: Any = None,
    ) -> None:
        self.workspace = workspace
        self._progress = progress or (lambda stage, detail: None)
        self._cancel = cancel
        self.registry = AdapterRegistry()
        self._bridges: dict[tuple[str, str], BridgePlan] = {}

    def _cancelled(self) -> bool:
        return bool(self._cancel is not None and self._cancel.is_set())

    # ------------------------------------------------------------------
    # main entry
    # ------------------------------------------------------------------

    def run(self, *, package_format: str | None = None, output: Path | None = None) -> FusionResult:
        fmt = package_format or self.workspace.config.package_format
        messages: list[str] = []
        start = time.time()

        self._progress("verify", "Checking workspace integrity")
        problems = self.workspace.verify()
        if problems:
            return self._fail(problems, messages, fmt)

        self._progress("graph", "Building the module graph")
        graph = build_graph(self.workspace)
        conflicts_snapshot = list(graph.conflicts)
        self.workspace.conflicts()  # duplicate/conflict detection is logged

        self._progress("bridges", "Planning module integrations")
        self._bridges = plan_all(graph, self.workspace)

        self._progress("compat", "Validating compatibility")
        compat = self.validate_compatibility(graph)
        fatal = [c["message"] for c in compat.checks if c["level"] == "error"]
        if fatal:
            return self._fail(fatal, messages, fmt, graph=graph, bridges=self._bridges, compat=compat)

        self._progress("build", "Building modules in dependency order")
        module_tasks: dict[str, BuildTask] = {}
        graph.tasks = []
        for module_id in graph.order:
            module = graph.module(module_id)
            if module is None:
                continue
            task = self._build_module(graph, module)
            module_tasks[module_id] = task
            graph.tasks.append(task)
            if self._cancelled():
                messages.append("Build cancelled by user.")
                break

        artifacts, artifact_paths = self._collect_artifacts(graph, module_tasks)
        self._verify_integration_architecture(graph, bridges=self._bridges, artifact_paths=artifact_paths)

        self._progress("assets", "Staging assets")
        asset_notes = self._stage_assets(graph)

        self._progress("assemble", "Assembling the application directory")
        assembly_dir = self.workspace.generated_dir / "app"
        if assembly_dir.exists():
            shutil.rmtree(assembly_dir)
        assembly_dir.mkdir(parents=True, exist_ok=True)
        assembly_notes = self._assemble(graph, artifacts, assembly_dir)

        self._progress("package", f"Packaging as {fmt}")
        package_path: Path | None = None
        package_error = ""
        try:
            package_path = self._package(assembly_dir, fmt, output)
        except Exception as exc:
            logger.debug("packaging failed: %s", exc)
            package_error = str(exc)

        validation: list[str] = []
        if package_path and package_path.exists() and fmt == "ece":
            validation = self._validate_ece(package_path)

        build_statuses = {t.status for t in module_tasks.values()}
        ok = (
            bool(module_tasks)
            and build_statuses.issubset({"built", "skipped"})
            and not package_error
            and not [v for v in validation if v.startswith("error")]
        )
        total_seconds = round(time.time() - start, 3)

        report = {
            "generated_utc": now_utc(),
            "workspace": str(self.workspace.root),
            "application": self.workspace.config.name,
            "version": self.workspace.config.version,
            "entry_point": graph.entry_point,
            "package_format": fmt,
            "package_path": str(package_path) if package_path else "",
            "assembly_dir": str(assembly_dir),
            "duration_seconds": total_seconds,
            "tasks": [t.to_dict() for t in module_tasks.values()],
            "ok": ok,
            "graph": graph.as_dict(),
            "bridges": [
                {"consumer": c, "provider": p, **plan.to_dict()}
                for (c, p), plan in sorted(self._bridges.items())
            ],
            "compatibility": {"checks": compat.checks, "warnings": compat.warnings},
            "assets": asset_notes,
            "assembly": assembly_notes,
            "planning_conflicts": conflicts_snapshot,
            "package_error": package_error,
            "validation": validation,
        }
        report_path = self.workspace.generated_dir / "report.json"
        report_path.write_text(
            json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        report["report_path"] = str(report_path)

        if package_error:
            messages.append(f"Packaging failed: {package_error}")
        messages.extend(conflicts_snapshot)
        if graph.cycles:
            messages.append("Dependency cycle present; module order may be incomplete.")

        return FusionResult(
            ok=ok,
            workspace=self.workspace,
            graph=graph,
            bridges=self._bridges,
            compatibility=compat,
            package_path=str(package_path) if package_path else "",
            package_kind=fmt,
            assembly_dir=str(assembly_dir),
            report=report,
            messages=messages,
            validation=validation,
        )

    def _fail(
        self,
        problems: list[str],
        messages: list[str],
        fmt: str,
        *,
        graph: ModuleGraph | None = None,
        bridges: dict | None = None,
        compat: CompatibilityReport | None = None,
    ) -> FusionResult:
        return FusionResult(
            ok=False,
            workspace=self.workspace,
            graph=graph or ModuleGraph(),
            bridges=bridges or {},
            compatibility=compat or CompatibilityReport(),
            package_kind=fmt,
            messages=messages + problems,
            report={"problems": problems},
        )

    # ------------------------------------------------------------------
    # building one module
    # ------------------------------------------------------------------

    def _build_module(self, graph: ModuleGraph, module: Module) -> BuildTask:
        if module.language == "assets":
            return BuildTask(
                task_id=f"module:{module.module_id}",
                module_id=module.module_id,
                title=f"stage assets ({module.module_id})",
                kind="asset",
                status="built",
            )

        task = BuildTask(
            task_id=f"module:{module.module_id}",
            module_id=module.module_id,
            title=f"build {module.module_id} ({module.build_tool or module.language})",
        )
        for dep in module.dependencies:
            task.depends_on.append(f"module:{dep}")

        root = self._module_root(module)
        try:
            scan_root = scan(root)
        except Exception as exc:
            task.status = "failed"
            task.error = f"Scan failed for module root: {exc}"
            module.status = "failed"
            return task
        adapter = None
        for d in self.registry.detect(root, scan_root):
            if d.adapter_id == module.adapter_id:
                adapter = self.registry.for_detected(d)
                break
        if adapter is None:
            task.status = "failed"
            task.error = f"No adapter plans builds for module {module.module_id}."
            module.status = "failed"
            return task

        requirements = adapter.inspect_requirements(root)
        if not requirements.ready:
            missing = [f"{r.id}: {r.install_hint}" for r in requirements.requirements if not r.found]
            task.status = "failed"
            task.error = "Toolchain missing; module NOT built (no fake success): " + "; ".join(missing)
            module.status = "failed"
            return task

        try:
            plan = adapter.create_build_plan(root)
        except Exception as exc:
            task.status = "failed"
            task.error = f"Build plan failed: {exc}"
            module.status = "failed"
            return task
        for step in plan.steps:
            task.command.append(" ".join(str(a) for a in step.cmd_args))

        log_path = self.workspace.generated_dir / f"build-{module.module_id}.log"
        started = time.time()
        result = adapter.execute_build(
            plan, progress=None, cancel=self._cancel, log_path=log_path, consent_granted=True
        )
        task.duration_seconds = round(time.time() - started, 3)
        task.status = "built" if result.ok else "failed"
        task.error = "" if result.ok else (result.message or "build failed")
        module.status = "built" if result.ok else "failed"
        return task

    def _module_root(self, module: Module) -> Path:
        inp = next(i for i in self.workspace.inputs if i.input_id == module.input_id)
        loc = self.workspace.input_location(inp)
        return loc / module.root if module.root else loc

    def _collect_artifacts(
        self, graph: ModuleGraph, tasks: dict[str, BuildTask]
    ) -> tuple[dict[str, list[Path]], dict[str, list[Path]]]:
        outputs: dict[str, list[Path]] = {}
        for module in graph.modules:
            task = tasks.get(module.module_id)
            if task is None or task.status != "built":
                continue
            root = self._module_root(module)
            found: list[Path] = []
            for name in module.output_artifacts:
                candidate = root / name
                for suffix in (".exe", ".dll", ".lib", ".pyd", ".so", ".node"):
                    if candidate.with_suffix(suffix).exists():
                        found.append(candidate.with_suffix(suffix))
            if not found:
                for out in ("bin", "build", "dist"):
                    folder = root / out
                    if folder.is_dir():
                        found.extend(
                            p for p in sorted(folder.rglob("*"))
                            if p.is_file()
                            and p.suffix.lower() in {".exe", ".dll", ".lib", ".so", ".pyd", ".node", ".a"}
                        )
            if found:
                outputs[module.module_id] = found
        return outputs, outputs

    # ------------------------------------------------------------------
    # compatibility
    # ------------------------------------------------------------------

    def validate_compatibility(self, graph: ModuleGraph) -> CompatibilityReport:
        report = CompatibilityReport()
        prebuilt: list[tuple[str, Path]] = []
        for module in graph.modules:
            root = self._module_root(module)
            for req in module.required_runtime:
                check_dotted_runtime(req, report)
            for suffix in (".dll", ".pyd", ".so", ".exe"):
                for candidate in sorted(root.rglob("*" + suffix))[:20]:
                    if candidate.is_file():
                        prebuilt.append((module.module_id, candidate))
        if prebuilt:
            for conflict in prebuilt_architecture_conflicts(self.workspace.root, prebuilt[:10]):
                report.add("error", conflict)
            for _module_id, path in prebuilt:
                if path.suffix.lower() == ".pyd":
                    check_python_extension_arch(path, report)
        for module in graph.modules:
            if module.language != "unreal":
                continue
            version = ""
            for req in module.required_runtime:
                if req.startswith("unreal-engine:"):
                    version = req.split(":", 1)[1]
            check_unreal_engine(version, report)
        return report

    def _verify_integration_architecture(
        self,
        graph: ModuleGraph,
        *,
        bridges: dict[tuple[str, str], BridgePlan],
        artifact_paths: dict[str, list[Path]],
    ) -> None:
        for (consumer_id, _provider_id), plan in bridges.items():
            if plan.method not in {"shared-library", "native-link", "python-extension", "c-abi"}:
                continue
            consumer = graph.module(consumer_id)
            provider = graph.module(plan.provider)
            if consumer and provider:
                for problem in verify_architecture_pair(consumer, provider, artifact_paths):
                    graph.conflicts.append(problem)

    # ------------------------------------------------------------------
    # assets, assembly, packaging
    # ------------------------------------------------------------------

    def _stage_assets(self, graph: ModuleGraph) -> list[str]:
        notes: list[str] = []
        has_unreal = any(m.language == "unreal" for m in graph.modules)
        for module in graph.modules:
            module.status = module.status
            if module.language != "assets":
                continue
            if has_unreal:
                notes.append(
                    f"{module.module_id}: raw assets are NOT auto-imported into the "
                    "engine; Unreal import/cook owns them (use an editor import "
                    "or a Python import script run before cooking)."
                )
            else:
                notes.append(f"{module.module_id}: staged raw asset folder.")
        return notes

    def _assemble(self, graph: ModuleGraph, artifacts: dict[str, list[Path]], assembly_dir: Path) -> list[str]:
        notes: list[str] = []
        entry_id = graph.entry_point
        entry_module = graph.module(entry_id) if entry_id else None
        unreal_modules = [m for m in graph.modules if m.language == "unreal"]

        for module in unreal_modules:
            notes.append(
                f"unreal module {module.module_id}: assembly goes through Unreal's "
                "own BuildCookRun pipeline; ECE only stages external modules "
                "around it and reports the engine's absence honestly."
            )

        for module in graph.modules:
            if module.status != "built" or module.language in {"assets", "unreal"}:
                continue
            root = self._module_root(module)
            if module.language == "python":
                target = assembly_dir if module.module_id == entry_id else assembly_dir / module.module_id
                target.mkdir(parents=True, exist_ok=True)
                for rel in module.source_files:
                    src = root / rel
                    dst = target / rel
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    try:
                        shutil.copy2(src, dst)
                    except OSError as exc:
                        notes.append(f"{module.module_id}: could not copy {rel}: {exc}")
                notes.append(f"python module {module.module_id} bundled as {target.name or 'app root'}")
            else:
                out_dir = assembly_dir / "modules" / module.module_id
                out_dir.mkdir(parents=True, exist_ok=True)
                for path in artifacts.get(module.module_id, []):
                    try:
                        shutil.copy2(path, out_dir / path.name)
                        notes.append(f"module {module.module_id}: deployed {path.name}")
                    except OSError as exc:
                        notes.append(f"module {module.module_id}: copy failed for {path.name}: {exc}")

        # Shared libraries consumed with ctypes sit next to the entry point.
        for (consumer_id, _provider_id), plan in self._bridges.items():
            if plan.method != "shared-library":
                continue
            provider = plan.provider
            for path in artifacts.get(provider, []):
                if path.suffix.lower() in _SHARED_DEPLOY_SUFFIXES:
                    shutil.copy2(path, assembly_dir / path.name)
                    notes.append(
                        f"shared library of '{provider}' placed next to the entry point (consumer '{consumer_id}')"
                    )

        # Generated launcher for a Python entry point.
        if entry_module and entry_module.language == "python":
            launcher = assembly_dir / "run_application.py"
            launcher.write_text(
                _LAUNCHER_TEMPLATE.format(
                    app_name=self.workspace.config.name,
                    entry_id=entry_id,
                ),
                encoding="utf-8",
            )
            notes.append(f"generated launcher: {launcher.name}")
        elif not entry_module and not unreal_modules:
            notes.append("no entry point: application files were assembled but no launcher was generated")
        return notes

    def _package(self, assembly_dir: Path, fmt: str, output: Path | None) -> Path:
        name = self.workspace.config.name or "application"
        version = self.workspace.config.version
        if output:
            destination = Path(output)
        else:
            suffix = {"ece": ".ece", "zip": ".zip"}.get(fmt, "")
            destination = self.workspace.generated_dir / f"{name}-{version}{suffix}"
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            destination.unlink()

        graph = build_graph(self.workspace)
        required_runtime: list[dict[str, Any]] = []
        for module in graph.modules:
            for req in module.required_runtime:
                required_runtime.append({"component": req, "module": module.module_id})
        entry = graph.module(graph.entry_point) if graph.entry_point else None

        manifest = Manifest(
            project_name=name,
            adapter_id="fusion",
            payload_type=f"fusion-application ({fmt})",
            platform=self.workspace.config.target_os,
            architecture=self.workspace.config.target_arch,
            configuration=self.workspace.config.configuration,
            entry_points=[{
                "module": graph.entry_point,
                "language": entry.language if entry else "",
                "kind": "module-entry",
            }] if graph.entry_point else [],
            runtime_requirements=required_runtime,
            notes="Assembled by the ECE fusion engine.",
        )
        manifest.unknown_fields["fusion_modules"] = [m.to_dict() for m in graph.modules]
        manifest.unknown_fields["fusion_graph"] = graph.as_dict()

        if fmt == "folder":
            return assembly_dir
        items = [
            PayloadItem(
                path=path.relative_to(assembly_dir).as_posix(),
                source=path,
                executable=path.suffix.lower() == ".exe",
            )
            for path in sorted(assembly_dir.rglob("*"))
            if path.is_file()
        ]
        if fmt == "ece":
            ContainerWriter().write(destination, items, manifest, overwrite=True)
            return destination
        import zipfile

        with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED) as zf:
            for path in sorted(assembly_dir.rglob("*")):
                if path.is_file():
                    zf.write(path, path.relative_to(assembly_dir.parent).as_posix())
        return destination

    def _validate_ece(self, package_path: Path) -> list[str]:
        findings: list[str] = []
        try:
            reader = ContainerReader(package_path)
            reader.open()
        except Exception as exc:
            return [f"error: package could not be parsed: {exc}"]
        try:
            findings.extend(f"error: {e}" for e in reader.verify_all())
            manifest = reader.manifest
        finally:
            reader.close()
        if manifest is None:
            findings.append("error: package has no manifest")
        elif manifest.payload_type and "fusion" not in manifest.payload_type:
            findings.append(f"warning: unexpected payload_type {manifest.payload_type!r}")
        return findings
