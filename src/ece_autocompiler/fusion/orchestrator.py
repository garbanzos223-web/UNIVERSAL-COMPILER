"""Fusion orchestrator: assembles one application from the module graph.

The pipeline follows the assembly order in docs/FUSION.md:

1. Verify the workspace and its inputs.
2. Build the module graph (imports, manifests, cycles, order).
3. Plan the bridges between pairs of modules.
4. Validate compatibility (architecture, runtime, toolchains).
5. Build every module with its own real toolchain, in dependency order.
6. Process/stage assets.
7. Assemble the application directory.
8. Package it (ECE container, ZIP or folder).
9. Validate the package and write the detailed report.

Every step records what actually happened; a step that could not run says so.
"""

