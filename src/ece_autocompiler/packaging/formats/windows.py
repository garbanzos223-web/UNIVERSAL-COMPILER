"""Windows installer formats: Inno Setup and NSIS.

Both formats drive a real installer compiler that must be installed on the
machine. When it is missing, the format says exactly what is missing and how
to install it - it never pretends to have produced an installer.

The generated scripts are plain text files, so the user can inspect exactly
what would be installed before the compiler runs.
"""

from __future__ import annotations

from pathlib import Path

from ..models import PackageRequest
from ..tools import run_tool, tool_path
from .base import FormatResult, PackageFormat, safe_name

#: Inno Setup and NSIS want Windows paths.
def _win_path(path: Path) -> str:
    return str(Path(path).resolve()).replace("/", "\\")


def _first_executable(staging: Path) -> str:
    for path in sorted(staging.rglob("*")):
        if path.is_file() and path.suffix.lower() in (".exe", ".bat", ".cmd"):
            return path.relative_to(staging).as_posix().replace("/", "\\")
    return ""


class InnoSetupFormat(PackageFormat):
    """A Windows installer compiled by Inno Setup (ISCC)."""

    fmt_id = "inno"
    display_name = "Windows installer (Inno Setup)"
    extension = "-setup.exe"
    tool_id = "inno-setup"

    def target_name(self, request: PackageRequest) -> str:
        metadata = request.metadata
        stem = f"{safe_name(metadata.name)}-{safe_name(metadata.version, '0.0.0')}"
        return stem + self.extension

    def script_text(self, staging: Path, request: PackageRequest, target: Path) -> str:
        metadata = request.metadata
        app_name = metadata.name or "Application"
        default_dir = f"{{autopf}}\\{app_name}"
        lines = [
            "; Generated by ECE Universal AutoCompiler.",
            "[Setup]",
            f"AppName={app_name}",
            f"AppVersion={metadata.version}",
        ]
        if metadata.description:
            lines.append(f"AppDescription={metadata.description}")
        if metadata.publisher:
            lines.append(f"AppPublisher={metadata.publisher}")
        lines.extend(
            [
                f"DefaultDirName={default_dir}",
                f"DefaultGroupName={app_name}",
                f"OutputDir={_win_path(target.parent)}",
                f"OutputBaseFilename={target.stem}",
                "Compression=lzma2",
                "SolidCompression=yes",
                "WizardStyle=modern",
                "DisableProgramGroupPage=yes",
                "ArchitecturesAllowed=x64compatible",
                "ArchitecturesInstallIn64BitMode=x64compatible",
                "",
                "[Files]",
                f'Source: "{_win_path(staging)}\\*"; DestDir: "{{app}}"; '
                "Flags: recursesubdirs ignoreversion",
            ]
        )
        entry = _first_executable(staging)
        if entry:
            lines.extend(
                [
                    "",
                    "[Icons]",
                    f'Name: "{{autoprograms}}\\{app_name}"; Filename: "{{app}}\\{entry}"',
                    "",
                    "[Run]",
                    f'Filename: "{{app}}\\{entry}"; Description: "Launch {app_name}"; '
                    "Flags: nowait postinstall skipifsilent",
                ]
            )
        return "\n".join(lines) + "\n"

    def build(
        self, staging: Path, request: PackageRequest, manifest: dict, target: Path
    ) -> FormatResult:
        script_path = Path(staging).parent / f"{target.stem}.iss"
        try:
            script_path.write_text(
                self.script_text(Path(staging), request, target), encoding="utf-8"
            )
        except OSError as exc:
            return FormatResult(
                ok=False,
                message=f"The Inno Setup script could not be written: {exc}",
                errors=[f"Check that {script_path.parent} is writable."],
            )
        code, output = run_tool(
            [tool_path(self.tool_id), str(script_path)],
            cwd=str(script_path.parent),
            timeout=request.timeout,
            reproducible=request.reproducible,
        )
        if code != 0:
            return FormatResult(
                ok=False,
                message="Inno Setup could not build the installer.",
                errors=[line for line in output.splitlines() if line.strip()][-12:]
                or ["Inno Setup reported no output."],
                notes=[f"Script kept at {script_path}"],
            )
        if not target.is_file():
            return FormatResult(
                ok=False,
                message="Inno Setup reported success but no installer was produced.",
                errors=[f"Expected file: {target}"],
                notes=[f"Script kept at {script_path}"],
            )
        return FormatResult(
            ok=True,
            path=target,
            message=f"Windows installer written to {target}",
            notes=[f"Script kept at {script_path}"],
        )


class NsisFormat(PackageFormat):
    """A Windows installer compiled by NSIS (makensis)."""

    fmt_id = "nsis"
    display_name = "Windows installer (NSIS)"
    extension = "-setup.exe"
    tool_id = "nsis"

    def target_name(self, request: PackageRequest) -> str:
        metadata = request.metadata
        stem = f"{safe_name(metadata.name)}-{safe_name(metadata.version, '0.0.0')}"
        return stem + self.extension

    def script_text(self, staging: Path, request: PackageRequest, target: Path) -> str:
        metadata = request.metadata
        app_name = metadata.name or "Application"
        entry = _first_executable(staging)
        lines = [
            "; Generated by ECE Universal AutoCompiler.",
            f'!define APPNAME "{app_name}"',
            f'!define APPVERSION "{metadata.version}"',
            f'!define OUTFILE "{_win_path(target)}"',
            "",
            'Name "${APPNAME} ${APPVERSION}"',
            'OutFile "${OUTFILE}"',
            'InstallDir "$PROGRAMFILES64\\${APPNAME}"',
            "RequestExecutionLevel admin",
            '!include "MUI2.nsh"',
            '!insertmacro MUI_PAGE_DIRECTORY',
            '!insertmacro MUI_PAGE_INSTFILES',
            '!insertmacro MUI_LANGUAGE "English"',
            "",
            'Section "Install"',
            '  SetOutPath "$INSTDIR"',
            f'  File /r "{_win_path(staging)}\\*"',
        ]
        if entry:
            lines.append(
                f'  CreateShortCut "$SMPROGRAMS\\${{APPNAME}}.lnk" "$INSTDIR\\{entry}"'
            )
        lines.extend(["SectionEnd", ""])
        return "\n".join(lines)

    def build(
        self, staging: Path, request: PackageRequest, manifest: dict, target: Path
    ) -> FormatResult:
        script_path = Path(staging).parent / f"{target.stem}.nsi"
        try:
            script_path.write_text(
                self.script_text(Path(staging), request, target), encoding="utf-8"
            )
        except OSError as exc:
            return FormatResult(
                ok=False,
                message=f"The NSIS script could not be written: {exc}",
                errors=[f"Check that {script_path.parent} is writable."],
            )
        code, output = run_tool(
            [tool_path(self.tool_id), str(script_path)],
            cwd=str(script_path.parent),
            timeout=request.timeout,
            reproducible=request.reproducible,
        )
        if code != 0:
            return FormatResult(
                ok=False,
                message="NSIS could not build the installer.",
                errors=[line for line in output.splitlines() if line.strip()][-12:]
                or ["NSIS reported no output."],
                notes=[f"Script kept at {script_path}"],
            )
        if not target.is_file():
            return FormatResult(
                ok=False,
                message="NSIS reported success but no installer was produced.",
                errors=[f"Expected file: {target}"],
                notes=[f"Script kept at {script_path}"],
            )
        return FormatResult(
            ok=True,
            path=target,
            message=f"Windows installer written to {target}",
            notes=[f"Script kept at {script_path}"],
        )
