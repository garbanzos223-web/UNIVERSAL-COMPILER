"""Base class and output helpers for decompilation backends."""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from ..models import (
    CATEGORY_CONFIG,
    CATEGORY_DISASSEMBLY,
    CATEGORY_METADATA,
    CATEGORY_RESOURCE,
    BackendOutput,
    FileAnalysis,
    RecoveredFile,
)

LogCallback = Callable[[str, str], None]

#: Files and folders that are build noise, never part of a recovered project.
NOISE_NAMES = {
    "__pycache__", ".git", ".svn", ".hg", "node_modules", ".venv", "venv",
    "bin", "obj", "target", "dist", "build", ".idea", ".vscode",
}


def is_noise(relative: str) -> bool:
    parts = Path(relative.replace("\\", "/")).parts
    return any(part in NOISE_NAMES for part in parts)


@dataclass
class BackendContext:
    output_dir: Path
    options: object
    log: LogCallback
    root: Path | None = None

    def __post_init__(self) -> None:
        self.output_dir = Path(self.output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def write_text(
        self,
        relative: str,
        text: str,
        *,
        category: str,
        status: str,
        provenance: str,
        language: str = "",
        editable: bool = True,
    ) -> RecoveredFile:
        target = self.output_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        return RecoveredFile(
            path=relative.replace("\\", "/"),
            category=category,
            status=status,
            provenance=provenance,
            language=language,
            disk_path=target,
            size=target.stat().st_size,
            editable=editable,
        )

    def write_bytes(
        self,
        relative: str,
        blob: bytes,
        *,
        category: str = CATEGORY_RESOURCE,
        status: str,
        provenance: str,
        language: str = "",
    ) -> RecoveredFile:
        target = self.output_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(blob)
        return RecoveredFile(
            path=relative.replace("\\", "/"),
            category=category,
            status=status,
            provenance=provenance,
            language=language,
            disk_path=target,
            size=len(blob),
            editable=False,
        )

    def copy_file(
        self,
        source: Path,
        relative: str,
        *,
        category: str = CATEGORY_RESOURCE,
        status: str,
        provenance: str,
    ) -> RecoveredFile:
        target = self.output_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            same = source.resolve() == target.resolve()
        except OSError:  # pragma: no cover - unusual path
            same = False
        if not same:
            shutil.copyfile(source, target)
        return RecoveredFile(
            path=relative.replace("\\", "/"),
            category=category,
            status=status,
            provenance=provenance,
            disk_path=target,
            size=target.stat().st_size,
            editable=False,
        )


class Backend:
    """Interface implemented by every decompilation backend."""

    id = ""
    label = ""
    kinds: tuple[str, ...] = ()

    def can_handle(self, analysis: FileAnalysis) -> bool:
        return analysis.format.kind in self.kinds

    def decompile(
        self, source: Path, analysis: FileAnalysis, ctx: BackendContext
    ) -> BackendOutput:  # pragma: no cover - interface
        raise NotImplementedError


def add_metadata(output: BackendOutput, ctx: BackendContext, name: str, payload: object) -> None:
    import json

    text = json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True)
    output.add(
        ctx.write_text(
            f"analysis/{name}.json",
            text,
            category=CATEGORY_METADATA,
            status="generated",
            provenance="Metadata read from the file headers.",
            language="json",
        )
    )


def add_disassembly(
    output: BackendOutput,
    ctx: BackendContext,
    name: str,
    text: str,
    note: str,
) -> None:
    body = f"# Disassembly generated by ECE Universal AutoCompiler\n# {note}\n\n{text or '(no instructions)'}\n"
    output.add(
        ctx.write_text(
            f"disassembly/{name}.asm",
            body,
            category=CATEGORY_DISASSEMBLY,
            status="generated",
            provenance="Disassembled instruction stream; not source code.",
            language="asm",
            editable=False,
        )
    )


def add_readme(output: BackendOutput, ctx: BackendContext, text: str) -> None:
    output.add(
        ctx.write_text(
            "README.txt",
            text,
            category=CATEGORY_CONFIG,
            status="generated",
            provenance="Explanation written by this tool about what was and was not recovered.",
            language="text",
        )
    )


